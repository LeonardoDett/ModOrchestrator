// RD15 (D128): an MO2 instance and a Vortex staging are imported end to end
// over the real store and filesystem; nothing is written in the other
// manager's folders; an interrupted import reopens with nothing left.

// mo2Fixture writes a global MO2 instance managing root and returns its
// folder. Mod order in modlist.txt is highest priority first.
func mo2Fixture(e *env, root string) string {
	dir := filepath.Join(e.dir, "LocalAppData", "ModOrganizer", "Skyrim")
	e.write(filepath.Join(dir, "ModOrganizer.ini"), "[General]\r\ngameName=Skyrim Special Edition\r\nselected_profile=@ByteArray(Default)\r\n"+
		"gamePath=@ByteArray("+strings.ReplaceAll(root, `\`, `\\`)+")\r\n\r\n[Settings]\r\nprofile_local_inis=false\r\n")
	e.write(filepath.Join(dir, "categories.dat"), "1|Animation|51|0\n2|Textures|29,30|0\n")
	mods := filepath.Join(dir, "mods")
	e.write(filepath.Join(mods, "Alpha", "meta.ini"), "[General]\r\nversion=1.2\r\ncategory=\"2,\"\r\ncomments=from mo2\r\n")
	e.write(filepath.Join(mods, "Alpha", "textures", "shared.dds"), "alpha")
	e.write(filepath.Join(mods, "Alpha", "Alpha.esp"), "alpha plugin")
	e.write(filepath.Join(mods, "Bravo", "textures", "shared.dds"), "bravo")
	e.write(filepath.Join(mods, "Charlie", "meshes", "c.nif"), "c")
	if err := os.MkdirAll(filepath.Join(mods, "Empty"), 0o755); err != nil {
		e.t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(mods, "Visuals_separator"), 0o755); err != nil {
		e.t.Fatal(err)
	}
	e.write(filepath.Join(dir, "overwrite", "SKSE", "generated.log"), "tool output")
	prof := filepath.Join(dir, "profiles", "Default")
	e.write(filepath.Join(prof, "modlist.txt"), "# This file was automatically generated by Mod Organizer.\r\n+Bravo\r\n+Alpha\r\n+Visuals_separator\r\n-Charlie\r\n-Empty\r\n*DLC: Dawnguard\r\n")
	e.write(filepath.Join(prof, pluginFileName(e)), "# generated\r\n*Alpha.esp\r\n")
	second := filepath.Join(dir, "profiles", "Second")
	e.write(filepath.Join(second, "modlist.txt"), "+Charlie\r\n-Bravo\r\n-Alpha\r\n")
	return dir
}

// pluginFileName is the plugin list the game reads (the adapter's name):
// the managers keep a copy of it in each profile.
func pluginFileName(e *env) string {
	return filepath.Base(skyrimse.Adapter{}.LoadOrderFile(e.inst).Path)
}

func (e *env) runImport(src migration.Source, opts imports.Options) *operation.Operation {
	e.t.Helper()
	id, err := e.imp.Start(ctx, e.inst.ID, src, opts)
	if err != nil {
		e.t.Fatal(err)
	}
	e.imp.Wait()
	return e.op(id)
}

func (e *env) profileNamed(name string) *profile.Profile {
	e.t.Helper()
	list, err := e.profiles.ListByInstance(ctx, e.inst.ID)
	if err != nil {
		e.t.Fatal(err)
	}
	for _, p := range list {
		if p.Name() == name {
			return p
		}
	}
	e.t.Fatalf("no profile %q", name)
	return nil
}

func (e *env) modsByName() map[string]*mod.Mod {
	e.t.Helper()
	list, err := e.mods.ListByInstance(ctx, e.inst.ID)
	if err != nil {
		e.t.Fatal(err)
	}
	out := map[string]*mod.Mod{}
	for _, m := range list {
		if m.State != mod.StateRemoved {
			out[m.Name] = m
		}
	}
	return out
}

func TestImportMO2Instance(t *testing.T) {
	e := newEnv(t)
	dir := mo2Fixture(e, e.inst.Root)
	before := snapshot(t, dir)

	srcs, err := e.imp.Sources(ctx, e.inst.ID)
	if err != nil || len(srcs) != 1 || srcs[0].Manager != game.ForeignMO2 {
		t.Fatalf("sources: %+v %v", srcs, err)
	}
	pv, err := e.imp.Preview(ctx, e.inst.ID, srcs[0])
	if err != nil {
		t.Fatal(err)
	}
	if pv.Mods != 4 || len(pv.Skipped) != 1 || pv.Skipped[0].Reason != imports.SkipEmpty || pv.Separators != 1 || pv.Categories != 1 {
		t.Fatalf("preview: %+v", pv)
	}
	for _, p := range []migration.Part{migration.PartMods, migration.PartOrder, migration.PartPlugins, migration.PartLoadOrder, migration.PartCategories} {
		if !slices.Contains(pv.Parts, p) {
			t.Fatalf("part %s missing: %v", p, pv.Parts)
		}
	}
	if slices.Contains(pv.Defaults, migration.PartCategories) {
		t.Fatalf("categories must be off by default: %v", pv.Defaults)
	}

	op := e.runImport(srcs[0], imports.Options{Profiles: []string{"Default", "Second"}})
	if op.Status != operation.StatusSucceeded {
		t.Fatalf("import: %+v", op.Error)
	}
	mods := e.modsByName()
	for _, n := range []string{"Alpha", "Bravo", "Charlie", "Overwrite"} {
		if m := mods[n]; m == nil || m.State != mod.StateInstalled {
			t.Fatalf("mod %s: %+v", n, m)
		}
	}
	if mods["Alpha"].Attributes.Version != "1.2" || mods["Alpha"].Category != "" {
		t.Fatalf("alpha attributes: %+v category %q", mods["Alpha"].Attributes, mods["Alpha"].Category)
	}
	if got := e.files(mods["Alpha"].ID); !slices.Equal(got, []string{"data:Alpha.esp", "data:textures/shared.dds"}) {
		t.Fatalf("alpha files (meta.ini must stay out): %v", got)
	}

	def := e.profileNamed("Default")
	var order []string
	for _, en := range def.Order() {
		if en.Separator != "" {
			sep, _ := def.Separator(en.Separator)
			order = append(order, "["+sep.Label+"]")
			continue
		}
		for n, m := range mods {
			if m.ID == en.Mod {
				order = append(order, n)
			}
		}
	}
	if want := []string{"Charlie", "[Visuals]", "Alpha", "Bravo", "Overwrite"}; !slices.Equal(order, want) {
		t.Fatalf("order %v, want %v", order, want)
	}
	if def.IsEnabled(mods["Charlie"].ID) || !def.IsEnabled(mods["Bravo"].ID) || !def.IsEnabled(mods["Overwrite"].ID) {
		t.Fatalf("enabled state wrong")
	}
	sec, err := plugin.StateOf(def)
	if err != nil {
		t.Fatal(err)
	}
	if on, known := sec.Enabled("Alpha.esp"); !on || !known {
		t.Fatalf("plugin state: %v %v", on, known)
	}
	second := e.profileNamed("Second")
	if !second.IsEnabled(mods["Charlie"].ID) || second.IsEnabled(mods["Alpha"].ID) {
		t.Fatalf("second profile enabled state wrong")
	}
	if active, _ := e.profiles.Active(ctx, e.inst.ID); active != def.ID() {
		t.Fatalf("active profile changed to %s", active)
	}
	if after := snapshot(t, dir); !maps.Equal(before, after) {
		t.Fatalf("the MO2 instance was changed")
	}
}

func TestImportMO2IntoGenericGame(t *testing.T) {
	e := newEnvWith(t, envOptions{generic: true})
	dir := mo2Fixture(e, e.inst.Root)
	srcs, err := e.imp.OpenFolder(ctx, dir)
	if err != nil || len(srcs) != 1 {
		t.Fatalf("open: %+v %v", srcs, err)
	}
	pv, err := e.imp.Preview(ctx, e.inst.ID, srcs[0])
	if err != nil {
		t.Fatal(err)
	}
	if slices.Contains(pv.Parts, migration.PartPlugins) || slices.Contains(pv.Parts, migration.PartLoadOrder) {
		t.Fatalf("a generic game lists no plugin parts: %v", pv.Parts)
	}
	if pv.Profiles[0].Plugins != 0 {
		t.Fatalf("plugins counted for a generic game: %+v", pv.Profiles)
	}
	op := e.runImport(srcs[0], imports.Options{Parts: []migration.Part{migration.PartMods, migration.PartOrder, migration.PartCategories}})
	if op.Status != operation.StatusSucceeded {
		t.Fatalf("import: %+v", op.Error)
	}
	mods := e.modsByName()
	if len(mods) != 4 || mods["Alpha"].Category == "" {
		t.Fatalf("mods: %d, alpha category %q", len(mods), mods["Alpha"].Category)
	}
}

// vortexFixture writes a Vortex data folder whose skyrimse game is root:
// three mods whose rules close a cycle, one profile.
func vortexFixture(e *env, root string) string {
	data := filepath.Join(e.dir, "AppData", "Vortex")
	staging := filepath.Join(data, "skyrimse", "mods")
	e.write(filepath.Join(staging, "A-1", "A.esp"), "a")
	e.write(filepath.Join(staging, "A-1", "textures", "x.dds"), "a")
	e.write(filepath.Join(staging, "B-1", "textures", "x.dds"), "b")
	e.write(filepath.Join(staging, "C-1", "meshes", "c.nif"), "c")
	e.write(filepath.Join(data, "skyrimse", "profiles", "p1", pluginFileName(e)), "*A.esp\r\n")
	db, err := leveldb.OpenFile(filepath.Join(data, "state.v2"), nil)
	if err != nil {
		e.t.Fatal(err)
	}
	put := func(v any, key ...string) {
		raw, _ := json.Marshal(v)
		if err := db.Put([]byte(strings.Join(key, "###")), raw, nil); err != nil {
			e.t.Fatal(err)
		}
	}
	put(root, "settings", "gameMode", "discovered", "skyrimse", "path")
	put("p1", "settings", "profiles", "lastActiveProfile", "skyrimse")
	rule := func(typ, id string) []map[string]any {
		return []map[string]any{{"type": typ, "reference": map[string]any{"id": id}}}
	}
	for i, m := range []struct {
		id, name, other string
	}{{"A-1", "Alpha", "B-1"}, {"B-1", "Bravo", "C-1"}, {"C-1", "Charlie", "A-1"}} {
		base := []string{"persistent", "mods", "skyrimse", m.id}
		put(m.id, append(base, "id")...)
		put("installed", append(base, "state")...)
		put(m.id, append(base, "installationPath")...)
		put("", append(base, "type")...)
		put(m.name, append(base, "attributes", "logicalFileName")...)
		put("2026-10-0"+string(rune('1'+i))+"T00:00:00Z", append(base, "attributes", "installTime")...)
		put(rule("after", m.other), append(base, "rules")...)
	}
	put("skyrimse", "persistent", "profiles", "p1", "gameId")
	put("Main", "persistent", "profiles", "p1", "name")
	put(true, "persistent", "profiles", "p1", "modState", "A-1", "enabled")
	put(true, "persistent", "profiles", "p1", "modState", "B-1", "enabled")
	put(false, "persistent", "profiles", "p1", "modState", "C-1", "enabled")
	if err := db.Close(); err != nil {
		e.t.Fatal(err)
	}
	return data
}

func TestImportVortexWithCyclicRules(t *testing.T) {
	e := newEnv(t)
	data := vortexFixture(e, e.inst.Root)
	before := snapshot(t, data)
	srcs, err := e.imp.Sources(ctx, e.inst.ID)
	if err != nil || len(srcs) != 1 || srcs[0].Manager != game.ForeignVortex {
		t.Fatalf("sources: %+v %v", srcs, err)
	}
	pv, err := e.imp.Preview(ctx, e.inst.ID, srcs[0])
	if err != nil {
		t.Fatal(err)
	}
	if pv.Mods != 3 || pv.OrderRules != 3 || slices.Contains(pv.Parts, migration.PartOrder) {
		t.Fatalf("preview: %+v", pv)
	}
	op := e.runImport(srcs[0], imports.Options{})
	if op.Status != operation.StatusSucceeded {
		t.Fatalf("a cycle among imported rules must not fail the import: %+v", op.Error)
	}
	set, err := e.rules.Get(ctx, e.inst.ID)
	if err != nil {
		t.Fatal(err)
	}
	if len(set.OrderRules()) != 3 {
		t.Fatalf("rules: %+v", set.OrderRules())
	}
	if _, cyclic := set.Cycle(); !cyclic {
		t.Fatalf("the cycle must be kept so the diagnostic reports it")
	}
	mods := e.modsByName()
	main := e.profileNamed("Main")
	if !main.IsEnabled(mods["Alpha"].ID) || main.IsEnabled(mods["Charlie"].ID) {
		t.Fatalf("enabled state wrong")
	}
	// A fresh library starts on the profile Vortex was using.
	if active, _ := e.profiles.Active(ctx, e.inst.ID); active != main.ID() {
		t.Fatalf("active profile %s, want %s", active, main.ID())
	}
	if after := snapshot(t, data); !maps.Equal(before, after) {
		t.Fatalf("the Vortex folder was changed")
	}
}

// killFS stops the import goroutine in the middle of the copy, the way a
// killed process would: nothing after that point runs.
type killFS struct {
	ports.FileSystem
	copies atomic.Int32
	at     int32
}

func (k *killFS) Copy(c context.Context, src, dst string) error {
	if k.copies.Add(1) == k.at {
		runtime.Goexit()
	}
	return k.FileSystem.Copy(c, src, dst)
}

func TestImportInterruptedLeavesNothing(t *testing.T) {
	dir := t.TempDir()
	var kill *killFS
	o := envOptions{dir: dir, dbPath: filepath.Join(dir, "state.db"), fs: func(f ports.FileSystem) ports.FileSystem {
		kill = &killFS{FileSystem: f, at: 3}
		return kill
	}}
	e := newEnvWith(t, o)
	mo := mo2Fixture(e, e.inst.Root)
	before := snapshot(t, mo)
	srcs, _ := e.imp.Sources(ctx, e.inst.ID)
	if _, err := e.imp.Start(ctx, e.inst.ID, srcs[0], imports.Options{}); err != nil {
		t.Fatal(err)
	}
	e.imp.Wait()
	if m := e.modsByName()["Alpha"]; m == nil || m.State != mod.StateInstalling {
		t.Fatalf("the kill must happen after the mods entered the library: %+v", m)
	}

	// Restart over the same database: startup recovery.
	r := newEnvWith(t, envOptions{dir: dir, dbPath: filepath.Join(dir, "state.db"), existing: true})
	if _, err := r.ops.RecoverInterrupted(ctx); err != nil {
		t.Fatal(err)
	}
	if err := r.imp.Recover(ctx); err != nil {
		t.Fatal(err)
	}
	if err := r.lib.Recover(ctx); err != nil {
		t.Fatal(err)
	}
	if left := r.modsByName(); len(left) != 0 {
		t.Fatalf("mods left by the interrupted import: %v", left)
	}
	entries, _ := os.ReadDir(r.inst.Staging)
	for _, en := range entries {
		if en.Name() != game.StagingMarker {
			t.Fatalf("left in the staging: %s", en.Name())
		}
	}
	if after := snapshot(t, mo); !maps.Equal(before, after) {
		t.Fatalf("the MO2 instance was changed")
	}
}
